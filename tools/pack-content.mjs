// node tools/pack-content.mjs — builds supabase/functions/course-content/_packed.ts, the only
// data the course-content function imports. Each course's bookData files are run in order (as
// the browser would), and the resulting { PARTS, CHAPTERS } is gzipped and base64-encoded. The
// raw files total ~7 MB and the CLI's Docker-less upload refuses that with a 413; packed they
// are under 3 MB. Registering a course means adding it here. Run by tools/deploy-content.sh.
import fs from "node:fs";
import vm from "node:vm";
import zlib from "node:zlib";

const DATA = new URL("../supabase/functions/course-content/_data/", import.meta.url);
const OUT = new URL("../supabase/functions/course-content/_packed.ts", import.meta.url);

const COURSES = {
  db: ["bookData-part1.js", "bookData-part2.js", "bookData-additions1.js",
       "bookData-additions2.js", "bookData-additions3.js", "bookData-part5.js"],
  rag: ["bookData-rag-part1.js", "bookData-rag-part2.js", "bookData-rag-part3.js", "bookData-rag-part4.js"],
  llm: ["bookData-llm-part1.js"],
  dsa: ["bookData-dsa-part1.js"],
};

let out = "// GENERATED by tools/pack-content.mjs — do not edit. base64(gzip(JSON { PARTS, CHAPTERS })).\n" +
          "export default {\n";
let total = 0;
for (const [key, files] of Object.entries(COURSES)) {
  const ctx = {};
  ctx.window = ctx; // the files assign window.PARTS / window.CHAPTERS, then push to bare CHAPTERS
  vm.createContext(ctx);
  for (const f of files) vm.runInContext(fs.readFileSync(new URL(f, DATA), "utf8"), ctx, { filename: f });
  if (!Array.isArray(ctx.PARTS) || !Array.isArray(ctx.CHAPTERS)) throw new Error(`${key}: no PARTS/CHAPTERS`);
  const b64 = zlib.gzipSync(JSON.stringify({ PARTS: ctx.PARTS, CHAPTERS: ctx.CHAPTERS }), { level: 9 }).toString("base64");
  total += b64.length;
  out += `  ${key}: "${b64}",\n`;
  console.log(`${key}: ${ctx.CHAPTERS.length} chapters, ${(b64.length / 1e6).toFixed(2)} MB packed`);
}
fs.writeFileSync(OUT, out + "} as Record<string, string>;\n");
console.log(`_packed.ts: ${(total / 1e6).toFixed(2)} MB` + (total > 4e6 ? " — WARNING: the 7 MB raw upload failed; approaching it again" : ""));
